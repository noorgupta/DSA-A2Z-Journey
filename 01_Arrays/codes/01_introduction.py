# Creating an array (Python List)

marks = [85, 92, 78, 95, 88]

print("Complete Array:")
print(marks)

print("-" * 30)

# Accessing elements using index

print("First Element:", marks[0])
print("Third Element:", marks[2])
print("Last Element:", marks[4])

print("-" * 30)

# Length of the array

print("Length:", len(marks))

print("-" * 30)

# Updating an element

marks[2] = 80

print("Updated Array:")
print(marks)