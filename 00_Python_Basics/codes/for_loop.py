# Example 1
print("range(stop)")
for i in range(5):
    print(i)

print("-" * 30)

# Example 2
print("range(start, stop)")
for i in range(2, 7):
    print(i)

print("-" * 30)

# Example 3
print("range(start, stop, step)")
for i in range(1, 10, 2):
    print(i)

print("-" * 30)

